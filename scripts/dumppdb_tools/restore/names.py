"""Turn PDB symbols into name-import files for disassemblers.

Only valid when the PDB belongs to the executable (same GUID and age); the
caller is expected to check that, see :func:`check_pdb_matches_exe`.
"""

from __future__ import annotations

import json
import re

from dumppdb_tools.restore.exe_analysis import PdbIdentity
from dumppdb_tools.restore.symbols import SymbolEntry


def check_pdb_matches_exe(pdb_info: dict[str, str], exe_identity: PdbIdentity) -> tuple[bool, str]:
    """Compare ``PdbApi_GetPdbInfo`` output with the exe's CodeView identity."""
    guid = pdb_info.get("guid", "")
    if not guid or not exe_identity.guid:
        return False, "GUID of the PDB or of the executable is unknown - cannot verify the match"
    if not exe_identity.matches(guid):
        return False, (f"PDB GUID {guid} does not match the executable "
                       f"({exe_identity.guid}); RVAs would be wrong")
    age = pdb_info.get("age", "")
    if age.isdigit() and int(age) != exe_identity.age:
        # The age legitimately differs when the PDB was re-linked/updated; the GUID is what matters.
        return True, f"GUID matches (PDB age {age}, exe age {exe_identity.age})"
    return True, "GUID and age match"


_SAFE = re.compile(r"[^0-9A-Za-z_]+")


def safe_identifier(name: str) -> str:
    s = _SAFE.sub("_", name).strip("_")
    if not s or s[0].isdigit():
        s = "_" + s
    return s


def collect_names(symbols: list[SymbolEntry]) -> list[dict]:
    """One entry per address: functions, data and public symbols with an RVA."""
    best: dict[int, dict] = {}
    # Publics first: typed symbols from the private part of the PDB override them.
    order = sorted(symbols, key=lambda s: 0 if s.is_public else 1)
    for s in order:
        if s.rva is None or s.rva == 0:
            continue
        if s.is_function or s.kind == "public-function":
            kind = "function"
        elif s.is_data or s.kind == "public-data":
            kind = "global"
        else:
            continue
        name = s.undecorated if (s.is_public and s.undecorated) else s.name
        best[s.rva] = {
            "rva": s.rva,
            "name": name,
            "kind": kind,
            "size": s.length,
            "comment": (f"{s.source}:{s.line}" if s.source else s.compiland),
        }

    entries = sorted(best.values(), key=lambda e: e["rva"])
    used: dict[str, int] = {}
    for e in entries:
        safe = safe_identifier(e["name"])
        n = used.get(safe, 0)
        used[safe] = n + 1
        e["safe"] = safe if n == 0 else f"{safe}_{e['rva']:X}"
    return entries


def ida_script(entries: list[dict], module: str) -> str:
    rows = "\n".join(
        f'    (0x{e["rva"]:X}, {json.dumps(e["safe"])}, {json.dumps(e["kind"])}, '
        f'{json.dumps(e["name"] + ("  // " + e["comment"] if e["comment"] else ""))}),'
        for e in entries)
    return f'''# Generated by DumpPDB from PDB symbols - names for {module}.
# Only run this on the executable the PDB was built with!
import idaapi, idc, ida_name

BASE = idaapi.get_imagebase()
NAMES = [
{rows}
]

applied = 0
for rva, name, kind, comment in NAMES:
    ea = BASE + rva
    if kind == "function":
        idc.add_func(ea)
    if ida_name.set_name(ea, name, ida_name.SN_NOWARN | ida_name.SN_NOCHECK | ida_name.SN_FORCE):
        applied += 1
    idc.set_cmt(ea, comment, 1)
print("DumpPDB: applied %d of %d names" % (applied, len(NAMES)))
'''


def ghidra_script(entries: list[dict], module: str) -> str:
    rows = "\n".join(
        f'    (0x{e["rva"]:X}, {json.dumps(e["safe"])}, {json.dumps(e["kind"])}, {json.dumps(e["name"])}),'
        for e in entries)
    return f'''# Generated by DumpPDB from PDB symbols - names for {module}.
#@category DumpPDB
from ghidra.program.model.symbol import SourceType

NAMES = [
{rows}
]

base = currentProgram.getImageBase()
applied = 0
for rva, name, kind, comment in NAMES:
    addr = base.add(rva)
    try:
        if kind == "function" and getFunctionAt(addr) is None:
            createFunction(addr, name)
        createLabel(addr, name, True, SourceType.USER_DEFINED)
        setEOLComment(addr, comment)
        applied += 1
    except Exception:
        pass
print("DumpPDB: applied %d of %d names" % (applied, len(NAMES)))
'''


def x64dbg_json(entries: list[dict], module: str) -> str:
    mod = module.lower()
    labels = [{"module": mod, "address": f"0x{e['rva']:X}", "manual": False, "text": e["safe"]}
              for e in entries]
    return json.dumps({"labels": labels}, indent=1)
